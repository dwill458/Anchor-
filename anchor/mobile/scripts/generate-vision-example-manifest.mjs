#!/usr/bin/env node
/**
 * Writes src/components/v2/vision/ceremony/visionExampleImages.ts from the example pictures on disk.
 * Metro needs a static require() per file, so run this after adding or replacing a picture:
 *   node scripts/generate-vision-example-manifest.mjs
 * Pictures live at src/assets/vision/examples/<category>/<1|2|3>.webp. Missing files are simply left out.
 */
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const examples = path.join(root, 'src/assets/vision/examples');
const out = path.join(root, 'src/components/v2/vision/ceremony/visionExampleImages.ts');
const CATEGORIES = ['desire', 'health', 'career', 'relationships', 'creativity', 'spirituality', 'abundance', 'family', 'learning', 'adventure', 'custom'];

const lines = [];
let count = 0;
for (const category of CATEGORIES) {
  const slots = [1, 2, 3].filter(slot => existsSync(path.join(examples, category, `${slot}.webp`)));
  if (!slots.length) continue;
  count += slots.length;
  lines.push(`  ${category}: {`);
  for (const slot of slots) lines.push(`    ${slot}: require('../../../../assets/vision/examples/${category}/${slot}.webp'),`);
  lines.push('  },');
}

writeFileSync(out, `// GENERATED by scripts/generate-vision-example-manifest.mjs. Do not edit by hand.
// One require() per file that exists in src/assets/vision/examples/<category>/<1|2|3>.webp.
import type { ImageSourcePropType } from 'react-native';
import type { AnchorCategory } from '@/types';

export const VISION_EXAMPLE_IMAGES: Partial<Record<AnchorCategory, Partial<Record<1 | 2 | 3, ImageSourcePropType>>>> = {
${lines.join('\n')}${lines.length ? '\n' : ''}};
`);
console.log(`Wrote ${path.relative(root, out)} with ${count} picture${count === 1 ? '' : 's'}.`);
