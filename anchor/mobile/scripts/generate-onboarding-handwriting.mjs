#!/usr/bin/env node
/**
 * Generates the pen-stroke data for onboarding Screen 2's handwritten intention.
 *
 * The strokes come from EMS Allure, a single-line (centreline) script font derived from Allura
 * by Sheldon B. Michaels, SIL Open Font License 1.1. A single-line font is what lets the screen
 * draw each letter along its own pen path instead of wiping a filled font on.
 *
 * Usage (the font ships in the `hersheytext` npm package):
 *   npm pack hersheytext && tar xzf hersheytext-*.tgz
 *   node scripts/generate-onboarding-handwriting.mjs package/svg_fonts/EMSAllure.svg
 *
 * Output: src/screens/v2/onboarding/handwritingStrokes.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LINES = ["A healthier me", "A stronger me"];
/** Glyph ends closer than this (font units) are one continuous pen movement. */
const JOIN_DISTANCE = 40;
const UNITS_PER_EM = 1000;

const fontPath = process.argv[2];
if (!fontPath) {
  console.error("usage: generate-onboarding-handwriting.mjs <EMSAllure.svg>");
  process.exit(1);
}
const svg = readFileSync(fontPath, "utf8");

const glyphs = new Map();
for (const match of svg.matchAll(/<glyph\s+([^>]*?)\/>/g)) {
  const attrs = Object.fromEntries(
    [...match[1].matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]),
  );
  if (attrs.unicode === undefined) continue;
  const unicode = attrs.unicode.replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)));
  glyphs.set(unicode, { advance: Number(attrs["horiz-adv-x"] ?? 378), d: attrs.d ?? "" });
}

function parseGlyph(d) {
  const strokes = [];
  let current = null;
  const tokens = d.trim() ? d.trim().split(/\s+/) : [];
  for (let i = 0; i < tokens.length; ) {
    const command = tokens[i++];
    const x = Number(tokens[i++]);
    const y = Number(tokens[i++]);
    if (command === "M") {
      current = [[x, y]];
      strokes.push(current);
    } else if (command === "L") {
      current.push([x, y]);
    } else {
      throw new Error(`Unsupported path command ${command}`);
    }
  }
  return strokes;
}

const round = (value) => Math.round(value * 1000) / 1000;

/** Chaikin corner cutting: the font's polylines read as smooth pen curves at display size. */
function smooth(points, iterations = 2) {
  let out = points;
  for (let n = 0; n < iterations; n++) {
    if (out.length < 3) return out;
    const next = [out[0]];
    for (let i = 0; i < out.length - 1; i++) {
      const [ax, ay] = out[i];
      const [bx, by] = out[i + 1];
      next.push([0.75 * ax + 0.25 * bx, 0.75 * ay + 0.25 * by], [0.25 * ax + 0.75 * bx, 0.25 * ay + 0.75 * by]);
    }
    next.push(out[out.length - 1]);
    out = next;
  }
  return out;
}

function layoutLine(text) {
  const strokes = [];
  let penX = 0;
  for (const char of text) {
    const glyph = glyphs.get(char);
    if (!glyph) throw new Error(`Glyph missing for "${char}"`);
    for (const raw of parseGlyph(glyph.d)) {
      // Font space is y-up; the screen is y-down. Units become ems.
      const points = raw.map(([x, y]) => [(penX + x) / UNITS_PER_EM, -y / UNITS_PER_EM]);
      const previous = strokes[strokes.length - 1];
      if (previous) {
        const [px, py] = previous[previous.length - 1];
        const [sx, sy] = points[0];
        if (Math.hypot(px - sx, py - sy) * UNITS_PER_EM < JOIN_DISTANCE) {
          previous.push(...points.slice(1));
          continue;
        }
      }
      strokes.push(points);
    }
    penX += glyph.advance;
  }
  return {
    text,
    width: round(penX / UNITS_PER_EM),
    strokes: strokes.map((raw) => {
      const points = smooth(raw);
      let length = 0;
      for (let i = 1; i < points.length; i++) {
        length += Math.hypot(points[i][0] - points[i - 1][0], points[i][1] - points[i - 1][1]);
      }
      return { length: round(length), points: points.flat().map(round) };
    }),
  };
}

const lines = LINES.map(layoutLine);
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/screens/v2/onboarding/handwritingStrokes.ts");
writeFileSync(
  out,
  `/**
 * GENERATED by scripts/generate-onboarding-handwriting.mjs — do not edit by hand.
 *
 * Pen strokes for Screen 2's handwritten intention, in ems (1 = font size), y down, origin at
 * the start of the baseline. Each stroke is one continuous pen movement: a flat x,y polyline.
 *
 * Letterforms: EMS Allure by Sheldon B. Michaels (derived from Allura by Rob Leuschke,
 * TypeSETit), SIL Open Font License 1.1.
 */
export type HandwritingStroke = { length: number; points: readonly number[] };
export type HandwritingLine = { text: string; width: number; strokes: readonly HandwritingStroke[] };

export const HANDWRITING_LINES: readonly HandwritingLine[] = ${JSON.stringify(lines)};
`,
);
console.log(`wrote ${out}`);
for (const line of lines) console.log(`${line.text}: ${line.strokes.length} strokes, width ${line.width}em`);
