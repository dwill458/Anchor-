#!/usr/bin/env node
/**
 * Generates src/components/v2/chart/map/chartFogFieldData.ts: the precomputed
 * fog field (nearest route distance, nearest arc, stipple noise) for the master
 * route, so the app decodes it instead of running ~63k noise + search
 * evaluations on the JS thread.
 *
 * Run from anchor/mobile:  node scripts/generate-chart-fog-field.mjs
 *
 * This mirrors buildRouteTable / buildFogFieldBruteForce in
 * src/components/v2/chart/map/chartMapGeometry.ts. The jest test
 * chartFogFieldData.test.ts proves the output matches the runtime build and that
 * the version hash matches the current route constants. After ANY change to the
 * route points, cell size, sample spacing or noise, re-run this script.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PTS = [
  [70, 992],
  [233, 790],
  [385, 606],
  [516, 490],
  // DEFERRED: [629, 380], [713, 292], [734, 190] placed the summit in the header zone.
  [575, 430],
  [625, 400],
  [660, 370],
];
const COLS = 213;
const ROWS = 295;
const CELL = 4;
const SPACING = 6;
const STEPS = 48;

// Must match fogRouteHashInput() in chartMapGeometry.ts exactly.
const hashInput = `fog-v1|${JSON.stringify(PTS)}|cell=${CELL}|cols=${COLS}|rows=${ROWS}|spacing=${SPACING}|steps=${STEPS}`;
function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

// ---- route samples (Float32 like the runtime table) ----
const sx = [];
const sy = [];
const sa = [];
let total = 0;
for (let i = 0; i < PTS.length - 1; i++) {
  const a = PTS[i];
  const b = PTS[i + 1];
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const L = Math.hypot(dx, dy);
  const nx = -dy / L;
  const ny = dx / L;
  const off = (i % 2 ? -1 : 1) * Math.min(34, L * 0.16);
  const c1x = a[0] + dx * 0.33 + nx * off;
  const c1y = a[1] + dy * 0.33 + ny * off;
  const c2x = a[0] + dx * 0.67 - nx * off * 0.7;
  const c2y = a[1] + dy * 0.67 - ny * off * 0.7;
  const bez = (t) => {
    const u = 1 - t;
    return [
      u * u * u * a[0] + 3 * u * u * t * c1x + 3 * u * t * t * c2x + t * t * t * b[0],
      u * u * u * a[1] + 3 * u * u * t * c1y + 3 * u * t * t * c2y + t * t * t * b[1],
    ];
  };
  let len = 0;
  let prev = bez(0);
  const tabT = [0];
  const tabL = [0];
  for (let k = 1; k <= STEPS; k++) {
    const p = bez(k / STEPS);
    len += Math.hypot(p[0] - prev[0], p[1] - prev[1]);
    tabT.push(k / STEPS);
    tabL.push(len);
    prev = p;
  }
  const n = Math.ceil(len / SPACING);
  for (let k = 0; k <= n; k++) {
    const arcL = (len * k) / n;
    let j = 1;
    while (j < tabL.length - 1 && tabL[j] < arcL) j++;
    const f = (arcL - tabL[j - 1]) / Math.max(1e-6, tabL[j] - tabL[j - 1]);
    const p = bez(tabT[j - 1] + (tabT[j] - tabT[j - 1]) * f);
    sx.push(Math.fround(p[0]));
    sy.push(Math.fround(p[1]));
    sa.push(Math.fround(total + arcL));
  }
  total += len;
}

// ---- noise ----
const hash1 = (n) => {
  const s = Math.sin(n * 127.1 + 311.7) * 43758.5453;
  return s - Math.floor(s);
};
const v2 = (x, y, s) => {
  const xi = Math.floor(x);
  const yi = Math.floor(y);
  const xf = x - xi;
  const yf = y - yi;
  const u = xf * xf * (3 - 2 * xf);
  const v = yf * yf * (3 - 2 * yf);
  const h = (p, q) => hash1(p * 57 + q * 131 + s * 7);
  return (h(xi, yi) * (1 - u) + h(xi + 1, yi) * u) * (1 - v) + (h(xi, yi + 1) * (1 - u) + h(xi + 1, yi + 1) * u) * v;
};

// ---- field ----
const n = COLS * ROWS;
const dist16 = new Uint16Array(n);
const arc16 = new Uint16Array(n);
const noise8 = new Uint8Array(n);
for (let my = 0; my < ROWS; my++) {
  const y = my * CELL + CELL / 2;
  for (let mx = 0; mx < COLS; mx++) {
    const x = mx * CELL + CELL / 2;
    let best = 1e12;
    let ba = 0;
    for (let k = 0; k < sx.length; k++) {
      const dx = sx[k] - x;
      const dy = sy[k] - y;
      const d = dx * dx + dy * dy;
      if (d < best) {
        best = d;
        ba = sa[k];
      }
    }
    const i = my * COLS + mx;
    dist16[i] = Math.round(Math.min(4095.9, Math.fround(Math.sqrt(best))) * 16);
    arc16[i] = Math.round(Math.min(4095.9, ba) * 16);
    const noise = Math.fround(0.5 * v2(mx * 0.12, my * 0.12, 3) + 0.25 * v2(mx * 0.35, my * 0.35, 5) + 0.25 * hash1(mx * 13 + my * 77));
    noise8[i] = Math.round(Math.min(1, Math.max(0, noise)) * 255);
  }
}

const u16le = (arr) => {
  const bytes = new Uint8Array(arr.length * 2);
  for (let i = 0; i < arr.length; i++) {
    bytes[i * 2] = arr[i] & 255;
    bytes[i * 2 + 1] = arr[i] >> 8;
  }
  return Buffer.from(bytes).toString('base64');
};

const out = `/* eslint-disable */
/**
 * GENERATED by scripts/generate-chart-fog-field.mjs. Do not edit by hand.
 * Precomputed fog field for the master route (see chartMapGeometry.ts).
 * - dist16 / arc16: little-endian Uint16 of round(value * 16), base64.
 * - noise8: Uint8 of round(noise * 255), base64.
 * hash: version of the route constants this data was generated for.
 */
export const FOG_FIELD_DATA = {
  hash: '${fnv1a(hashInput)}',
  cols: ${COLS},
  rows: ${ROWS},
  dist16: '${u16le(dist16)}',
  arc16: '${u16le(arc16)}',
  noise8: '${Buffer.from(noise8).toString('base64')}',
} as const;
`;

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/components/v2/chart/map/chartFogFieldData.ts');
writeFileSync(target, out);
console.log(`wrote ${target} (${(out.length / 1024).toFixed(0)} KB), hash ${fnv1a(hashInput)}`);
