"""Import approved vectors without drawing, simplifying, or recolouring them.

Run from any directory; --check verifies the checked-in import against its source.
XML parsing rejects unsupported geometry so a new package cannot silently lose art.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

MOBILE = Path(__file__).resolve().parents[1]
SOURCE = MOBILE.parents[1] / 'design/milestones/approved-20261021'
OUTPUT = MOBILE / 'src/milestones/approvedAssets.generated.ts'
MAPPING = {
    'strength.building': 'strength_building',
    'strength.established': 'strength_established',
    'strength.integrated': 'strength_integrated',
    'strength.reinforced': 'strength_reinforced',
    'strength.full': 'strength_full_strength',
    'commitment.practices.1': 'commitment_first_practice',
    'commitment.practices.10': 'commitment_ten_practices',
    'commitment.practices.30': 'commitment_thirty_practices',
    'commitment.practices.100': 'commitment_one_hundred_practices',
    'commitment.minutes.100': 'commitment_100_minutes',
    'commitment.minutes.500': 'commitment_500_minutes',
    'journey.waypoint.first': 'journey_first_waypoint',
    'journey.halfway': 'journey_halfway',
    'journey.destination': 'journey_all_waypoints',
    'journey.goal': 'journey_goal_reached',
    'vision.first': 'vision_first_glimpse',
    'vision.board.complete': 'vision_picture_complete',
    'vision.visualize.1': 'vision_seen_clearly',
    'vision.visualize.10': 'vision_familiar_future',
    'vision.visualize.30': 'vision_living_the_vision',
}
TAGS = {'svg', 'g', 'defs', 'circle', 'line', 'path', 'rect', 'ellipse',
        'polygon', 'polyline', 'linearGradient', 'radialGradient', 'stop', 'clipPath'}

def parse(element):
    tag = element.tag.rsplit('}', 1)[-1]
    if tag in {'title', 'desc'}:
        return None
    if tag not in TAGS:
        raise ValueError(f'Unsupported SVG tag {tag}')
    attrs = {}
    for key, value in element.attrib.items():
        if key in {'role', 'aria-label'}:
            continue
        if key.startswith('{') or key in {'style', 'filter', 'class'}:
            raise ValueError(f'Unsupported SVG attribute {key}')
        attrs[re.sub(r'-([a-z])', lambda m: m[1].upper(), key)] = value
    return {'tag': tag, 'attrs': attrs,
            'children': [node for child in element if (node := parse(child)) is not None]}

def main():
    manifest = json.loads((SOURCE / 'docs/animation-manifest.json').read_text())
    for state in ('earned', 'locked'):
        inventory = {path.stem for path in (SOURCE / f'svg/{state}').glob('*.svg')}
        if inventory != set(MAPPING.values()):
            raise ValueError(f'{state} package inventory does not match explicit milestone map')
    assets = {}
    for milestone, slug in MAPPING.items():
        asset = {'slug': slug, 'manifest': manifest[slug], 'sourceSha256': {}}
        for state in ('earned', 'locked'):
            path = SOURCE / f'svg/{state}/{slug}.svg'
            raw = path.read_bytes()
            root = ET.fromstring(raw)
            assert root.get('viewBox') == '0 0 256 256'
            asset[state] = parse(root)
            asset['sourceSha256'][state] = hashlib.sha256(raw).hexdigest()
        assets[milestone] = asset
    content = ('// Generated by scripts/import-approved-milestones.py; do not edit.\n'
               '// Approved source retains screenshot reconstructions; see design handoff.\n'
               "import type { ApprovedMilestoneAsset } from './approvedAssets';\n"
               'export const APPROVED_MILESTONE_ASSETS: Readonly<Record<string, ApprovedMilestoneAsset>> = '
               + json.dumps(assets, separators=(',', ':')) + ';\n')
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Approved asset import differs from package; run importer.')
    else:
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'Validated {len(assets)} milestones / 40 SVGs; no unsupported SVG features.')

if __name__ == '__main__':
    main()
