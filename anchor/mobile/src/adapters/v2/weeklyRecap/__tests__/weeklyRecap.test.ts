import AsyncStorage from '@react-native-async-storage/async-storage';
import fixture from '../__fixtures__/weeklyRecapV2.sample.json';
import { isWeeklyRecap, type WeeklyRecap } from '../types';
import { readCachedRecap, writeCachedRecap } from '../weeklyRecapCache';
import { canOpenAnchor, itemLabel, motionForDisplay, nextActionFor, provisionalNotice, statsForDisplay } from '../weeklyRecapViewModel';

const recap = fixture as unknown as WeeklyRecap;
const clone = (patch: Partial<WeeklyRecap> = {}): WeeklyRecap => ({ ...JSON.parse(JSON.stringify(recap)), ...patch });

describe('contract with the server (fixture generated by the backend composer)', () => {
  it('accepts the server fixture', () => expect(isWeeklyRecap(fixture)).toBe(true));
  it('rejects anything it does not fully understand', () => {
    expect(isWeeklyRecap(null)).toBe(false);
    expect(isWeeklyRecap({ ...recap, recapVersion: 3 })).toBe(false);
    expect(isWeeklyRecap({ ...recap, motion: recap.motion.slice(0, 6) })).toBe(false);
    expect(isWeeklyRecap({ ...recap, hero: { kind: 'WAYPOINT_REACHED' } })).toBe(false);
    expect(isWeeklyRecap({ ...recap, status: 'MAYBE' })).toBe(false);
  });
});

describe('view model', () => {
  it('explains provisional status accurately for every reason, and nothing when final', () => {
    const p = (reason: any, isProvisional = true) => provisionalNotice(clone({ provisional: { isProvisional, reason } }));
    expect(p('WEEK_IN_PROGRESS')).toMatch(/so far/);
    expect(p('SYNCING')).toMatch(/Tuesday at noon/);
    expect(p('INCOMPLETE_DATA')).toMatch(/could not be loaded/);
    expect(p(null, false)).toBeNull();
    expect(provisionalNotice(recap)).toBeNull();
  });
  it('formats counts with their own singular/plural and spoken labels', () => {
    const stats = statsForDisplay(recap);
    expect(stats.find(s => s.id === 'PRACTICE_DAYS')).toMatchObject({ value: '3 of 7', label: 'Practice days' });
    expect(stats.find(s => s.id === 'WAYPOINTS')).toMatchObject({ value: '1', label: 'Waypoint', spoken: '1 waypoint' });
    expect(stats.find(s => s.id === 'MOVES')).toMatchObject({ value: '2', label: 'Moves' });
  });
  it('describes each day for screen readers, including an empty one', () => {
    const days = motionForDisplay(recap);
    expect(days).toHaveLength(7);
    expect(days.find(d => d.dateKey === '2026-10-14')!.spoken).toBe('Wednesday: 1 move');
    expect(days.find(d => d.dateKey === '2026-10-17')!.spoken).toBe('Saturday: nothing recorded');
  });
  it('names a batch of moves by count and a single move by title', () => {
    expect(itemLabel({ ...recap.hero, kind: 'MOVES_PROGRESS', count: 3, title: '3 moves' })).toBe('3 moves finished');
    expect(itemLabel({ ...recap.hero, kind: 'MOVES_PROGRESS', count: 1, title: 'Email an editor' })).toBe('Email an editor');
  });
  it('only links Anchors that can be opened here', () => {
    expect(canOpenAnchor('a1', new Set(['a1']))).toBe(true);
    expect(canOpenAnchor('a2', new Set(['a1']))).toBe(false);
  });
  it('offers a Chart next step for chart progress, an Anchor step otherwise, and nothing for released or unopenable Anchors', () => {
    const open = new Set(['a1']);
    expect(nextActionFor(recap, undefined, open)).toEqual({ label: 'See your next move', target: 'CHART', anchorId: 'a1' });
    expect(nextActionFor(clone({ hero: { ...recap.hero, kind: 'PRACTICE_WEEK' } }), undefined, open)).toMatchObject({ target: 'ANCHOR', label: 'Continue with Write and publish my book' });
    expect(nextActionFor(recap, undefined, new Set())).toBeNull();
    const released = clone(); released.refs.anchors.a1.isReleased = true;
    expect(nextActionFor(released, undefined, open)).toBeNull();
  });
});

describe('offline cache', () => {
  beforeEach(async () => { await AsyncStorage.clear(); });
  const entry = (r: WeeklyRecap) => ({ id: 'snap', recap: r, feedback: null, updatedAt: '' });
  it('round-trips and resolves "latest"', async () => {
    await writeCachedRecap(entry(recap), true);
    expect((await readCachedRecap('2026-10-12'))?.recap.weekKey).toBe('2026-10-12');
    expect((await readCachedRecap('latest'))?.id).toBe('snap');
  });
  it('never replaces a final copy with a draft', async () => {
    await writeCachedRecap(entry(recap), false);
    await writeCachedRecap(entry(clone({ status: 'DRAFT' })), false);
    expect((await readCachedRecap('2026-10-12'))?.recap.status).toBe('FINAL');
  });
  it('ignores a corrupt or outdated entry', async () => {
    await AsyncStorage.setItem('anchor.weeklyRecap.v2.2026-10-12', JSON.stringify({ recap: { recapVersion: 1 } }));
    expect(await readCachedRecap('2026-10-12')).toBeNull();
    await AsyncStorage.setItem('anchor.weeklyRecap.v2.2026-10-19', '{not json');
    expect(await readCachedRecap('2026-10-19')).toBeNull();
  });
});
